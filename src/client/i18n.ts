export const CLIENT_LOCALE_DICTS = { zh, en } as const;

export function createFallbackTranslator(lang: 'zh' | 'en' = 'en'): ClientTranslateFn {
  const dict = lang === 'zh' ? zh : en;
  return (key, params) => {
    const template = (dict as Record<string, string>)[key] ?? (en as Record<string, string>)[key] ?? key;
    if (!params) return template;
    return template.replace(/\{(\w+)\}/g, (match, name: string) =>
      name in params && params[name] !== undefined && params[name] !== null
        ? String(params[name])
        : match,
    );
  };
}
